function answerPlatformFaq(message, history = []) {
  const m = String(message || "").trim();
  const lastUser = [...history].reverse().find((h) => h.role === "user")?.content || "";

  if (/^(منطقة|المنطقة|مناطق)$/i.test(m)) {
    return "اختر منطقتك من كروت المناطق بالأسفل، أو اكتب اسم منطقة (مثل: حائل).";
  }

  if (/فكرة|وش (ال)?منص|ما (هي|فائدة)|عن المنص|عشيبة السعودية|اكتشف ريف|ريف السعودية|وش تقدم|وش تسو/i.test(m)) {
    return (
      "«عشيبة السعودية الريفية» تجمع تجارب الريف السعودي في مكان واحد — من محميات وتطعيس إلى مزارع وتراث وإقامة.\n\n" +
      "هدفنا نربطك بتجارب أصيلة قريبة منك، مع قصص تراثية وحجز مباشر. اختر من الكروت أو قُل لي وش يناسبك (عائلات، شباب، أو منطقة معيّنة)."
    );
  }

  if (/كيف (أ|ا)حجز|طريقة الحجز|خطوات الحجز/i.test(m)) {
    return (
      "الحجز بسيط: اختر تجربة من الكروت أو من الصفحة الرئيسية → اضغط «احجز» → أدخل بياناتك وعدد الأشخاص → تأكيد.\n\n" +
      "أو قُل لي «أبي أحجز» وأقترح لك تجربة مناسبة."
    );
  }

  if (/من (أ|ا)نت|وش عشيب|عشيبة|دورك|مساعد/i.test(m)) {
    return (
      "أنا عشيبة، مرشدتك الريفية الذكية في المنصة. أساعدك في:\n" +
      "• اقتراح تجارب حسب اهتمامك ومنطقتك\n" +
      "• الحجز والاستفسار\n" +
      "• استكشاف القصص التراثية\n\n" +
      "اسألني عن المنصة أو عن تجربة معيّنة."
    );
  }

  if (/مناطق|أي مناطق|وين (تغط|موجود)/i.test(m)) {
    return (
      "نغطي مناطق متعددة في المملكة — من حائل وعسير إلى الأحساء والطائف وجازان وغيرها.\n" +
      "اختر منطقتك من الكروت أو من القائمة، وأعرض لك ما يتوفر فيها."
    );
  }

  if (/سعر|أسعار|بكم|كم (السعر|تكلف)/i.test(m)) {
    return (
      "كل تجربة لها سعرها ومدتها على الكرت — تختلف حسب النشاط.\n" +
      "اختر تجربة لترى السعر، أو قُل لي منطقتك ونوع النشاط لأقترح خيارات."
    );
  }

  if (/تسجيل|حساب|دخول/i.test(m)) {
    return (
      "يمكنك التصفح كزائر. للحجز الكامل وقراءة القصص كاملة، سجّل دخولك برقم الجوال من زر «تسجيل الدخول» في أعلى الصفحة."
    );
  }

  return (
    "«عشيبة السعودية الريفية» منصة لاستكشاف وحجز تجارب ريفية أصيلة في المملكة — طبيعة، تراث، مغامرة، وزراعة.\n\n" +
    "إذا تحب، قُل لي: وش تقترحين؟ أو اختر من الكروت (عائلات / شباب / منطقة)."
  );
}

module.exports = { PLATFORM_KNOWLEDGE, answerPlatformFaq };
